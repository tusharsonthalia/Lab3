"""Independent provenance check for predictions.md.

For each section of predictions.md, find the earliest Pi transcript snapshot in which the agent
read that section's exact text, and compare that time with the first run the section governs.
Evidence comes only from the unedited Pi transcripts and results/runs.jsonl. Output:
results/predictions_provenance.md"""
import glob, json, os, re, datetime as dt

def norm(s): return re.sub(r"\s+", " ", s).strip()
def iso(ms): return dt.datetime.fromtimestamp(ms / 1000, dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")

# 1. snapshots: every tool result that contains predictions.md text, timestamped by the
#    assistant message that issued the call (message_end timestamp, epoch ms).
snaps = []
for f in sorted(glob.glob("transcripts/*.jsonl")):
    last_ts, pending = None, {}
    for line in open(f):
        e = json.loads(line)
        t = e.get("type")
        if t == "message_end" and e["message"].get("role") == "assistant":
            last_ts = e["message"].get("timestamp")
        elif t == "tool_execution_start":
            if "predictions.md" in json.dumps(e.get("args") or {}):
                pending[e["toolCallId"]] = last_ts
        elif t == "tool_execution_end" and e.get("toolCallId") in pending:
            txt = "".join(c.get("text", "") for c in (e.get("result") or {}).get("content", []) if isinstance(c, dict))
            snaps.append((pending.pop(e["toolCallId"]), os.path.basename(f), norm(txt)))
snaps.sort(key=lambda s: s[0] or 0)

# 2. sections of the current file (## and ### headings), compared by body text
cur = open("predictions.md").read()
parts = re.split(r"(?m)^(#{2,3} .+)$", cur)
# Line-level matching: the agent sometimes read the file in chunks (head/sed ranges), and later
# appended separators ("---") follow some sections. A section is verified at time T when the
# heading and every non-separator line of its body appear in agent snapshots taken at or before T.
def lines_of(head, body):
    ls = [norm(head)] + [norm(x) for x in body.splitlines()]
    return [x for x in ls if x and x != "---"]
sections = [(parts[i].strip(), lines_of(parts[i], parts[i + 1])) for i in range(1, len(parts) - 1, 2)]

# 3. first governed run per section (earliest record timestamp of the governed class)
runs = [json.loads(l) for l in open("results/runs.jsonl") if l.strip()]
def first(pred):
    ts = [r["timestamp"] for r in runs if pred(r)]
    return min(ts)[:19].replace("T", " ") + "Z" if ts else "—"
gov = {
    "Part A": ("first dense training run", first(lambda r: r.get("part") == "A" and r.get("command") == "train")),
    "Part B": ("first Part B pruning run (smoke)", first(lambda r: r.get("part") == "B")),
    "B.6": ("first pilot-matrix run", first(lambda r: r.get("phase") == "pilot")),
    "B.7": ("first confirmatory run", first(lambda r: r.get("phase") == "confirm")),
    "Part C": ("first Part C run", first(lambda r: r.get("part") == "C")),
    "C.3": ("first Part C run", first(lambda r: r.get("part") == "C")),
}
def governs(h):
    for k in ("B.6", "B.7", "C.3"):
        if k in h: return gov[k]
    for k in ("Part A", "A.1", "A.2"):
        if k in h: return gov["Part A"]
    for k in ("Part B", "B.1", "B.2", "B.3", "B.4", "B.5"):
        if k in h: return gov["Part B"]
    for k in ("Part C", "C.1", "C.2"):
        if k in h: return gov["Part C"]
    return ("—", "—")

out = ["# predictions.md provenance (generated by scripts/predictions_provenance.py)", "",
       "This file shows when every line of each section first appeared in what the agent read, in the unedited Pi",
       "transcripts, and compares that time with the first run the section governs.",
       "`predictions.md` is append-only: corrections are added as dated amendments, never as edits.",
       "A section with no snapshot simply was not read by the agent. It may still predate its runs,",
       "but the transcripts give no independent proof of that.", "",
       "| Section | All lines seen by agent by (UTC) | Transcript | Governs | First governed run (UTC) | Snapshot precedes run? |",
       "|---|---|---|---|---|---|"]
for h, body in sections:
    hit, first_seen = None, []
    for ln in body:
        m = next(((ts, f) for ts, f, txt in snaps if ts and ln in txt), None)
        if m is None: first_seen = None; break
        first_seen.append(m)
    if first_seen: hit = max(first_seen, key=lambda m: m[0])
    what, when = governs(h)
    if hit:
        sw = iso(hit[0]); ok = "yes" if when != "—" and sw < when else ("n/a" if when == "—" else "**NO**")
        out.append(f"| {h.lstrip('#').strip()} | {sw} | {hit[1]} | {what} | {when} | {ok} |")
    else:
        out.append(f"| {h.lstrip('#').strip()} | not read verbatim by agent | — | {what} | {when} | unverified |")
open("results/predictions_provenance.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
